export function translate(language, key) {
  if (typeof key !== "string") return key
  if (Object.hasOwn(languageNames, key)) return languageNames[key]
  const orderNotification = key.match(/^Your order (.+) for (₹[\d,.]+) has been placed and is now pending dispatch\.$/)
  if (orderNotification && language === "hi") {
    return `आपका ऑर्डर ${orderNotification[1]} (${orderNotification[2]}) दर्ज हो गया है और भेजे जाने की प्रतीक्षा में है।`
  }
  if (orderNotification && language === "ta") {
    return `உங்கள் ஆர்டர் ${orderNotification[1]} (${orderNotification[2]}) பதிவு செய்யப்பட்டது; அனுப்புவதற்காகக் காத்திருக்கிறது.`
  }
  if (language !== "hi" && language !== "ta") {
    const englishTranslation = englishTranslations[key]
    if (englishTranslation) return englishTranslation
    for (const dictionary of Object.values(translations)) {
      const original = Object.entries(dictionary).find(([, value]) => value === key)?.[0]
      if (original) return original
    }
    for (const [original, values] of Object.entries(productNameTranslations)) {
      if (values.includes(key)) return original
    }
    return key
  }
  for (const [original, value] of Object.entries(translations[language] || {})) {
    if (value === key) return value
  }
  for (const values of Object.values(translations)) {
    const original = Object.entries(values).find(([, value]) => value === key)?.[0]
    if (original) key = original
  }
  for (const [original, values] of Object.entries(productNameTranslations)) {
    if (values[language === "hi" ? 0 : 1] === key) key = original
  }
  const translated = translations[language]?.[key] || englishTranslations[key]
  if (translated) return translated

  const productTranslation = productNameTranslations[key.trim().toLowerCase()]
  if (productTranslation) return productTranslation[language === "hi" ? 0 : 1] || key

  return Object.keys(productNameTranslations)
    .sort((a, b) => b.length - a.length)
    .reduce((value, name) => value.replace(new RegExp(`\\b${name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi"), productNameTranslations[name][language === "hi" ? 0 : 1]), key)
}

export default function useLanguage() {
  const [language, setLanguage] = useState(() => {
    if (typeof window === "undefined") return "en"
    const saved = window.localStorage.getItem("cf-language")
    return saved === "hi" || saved === "ta" ? saved : "en"
  })

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const changeLanguage = (nextLanguage) => {
    if (!["en", "hi", "ta"].includes(nextLanguage)) return
    window.localStorage.setItem("cf-language", nextLanguage)
    setLanguage(nextLanguage)
  }

  return { language, setLanguage: changeLanguage, t: (key) => translate(language, key) }
}
